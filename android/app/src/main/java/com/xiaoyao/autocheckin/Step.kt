package com.xiaoyao.autocheckin

/**
 * 一条签到步骤。
 *
 * kind 取值：
 *  - tab     切底部 Tab / 会话项（desc 或 text 匹配）；入口已直达通知中心时自动跳过
 *  - wait    只等目标出现、不点击（value 按 text 匹配）；页面卡住时靠它超时触发重试
 *  - text    按控件显示文字查找
 *  - id      按控件资源 id 查找（可写短名 btn_submit，也可写全名 com.xx:id/btn_submit）
 *  - desc    按 contentDescription 查找
 *  - cls     按类名查找（如 android.widget.Button）
 *  - uni     按【字体图标码点】匹配 text（value 写十六进制，如 e62b）
 *  - uiwait  同 uni，但只等它出现、不点击
 *  - sleep   什么都不做，只静置 value 毫秒（value 直接写毫秒数，如 2500）
 *  - xy      按坐标点击。value 写 "540,1800"（绝对像素）或 "50%,86%"（屏幕比例，推荐）
 *  - scroll  滚动当前可滚动容器到底部（value 写 down 即可）
 *
 * sleep 的用处：H5 页面「DOM 渲染完」不等于「内部组件就绪」——
 * 地图、定位、相机这些是异步初始化的，页面文案都出来了，点里面的按钮仍然可能没反应。
 * 真机实测（2026-09-25）签到页就是这种：等待文案出现后立刻操作，时好时坏。
 *
 * uni / uiwait 是为一类「没有 id、没有 contentDescription」的私有字体图标准备的：
 * 签到页的「拍照」入口就是这种，text 直接就是一个私用区码点（\ue62b），
 * 在编辑框里显示成空白方块。实测它有 clickable、且位置跨机型稳定，
 * 比坐标（xy）可靠得多 —— 坐标一换分辨率就废。
 *
 * 界面上的文本格式（每行一条，以 # 开头为注释）：
 *   kind|value|contains|optional|waitMs|last
 *   后四段可省略，例：text|提交
 *
 * last = 1 时，若匹配到多个控件则取【最后一个】。
 * 真机侦察结论：目标 App 的消息列表是「旧 → 新」排列，最新的签到提醒在最下面，
 * 因此点卡片必须用 last=1，否则会点到最旧的那条。
 */
data class Step(
    val kind: String,
    val value: String,
    val contains: Boolean = false,
    val optional: Boolean = false,
    val waitMs: Long = 8000L,
    val last: Boolean = false
